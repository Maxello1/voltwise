function base(
  topicId: string,
  id: string,
  title: string,
  prompt: string,
  explanation: string,
  hint: string,
  difficulty: 1 | 2 | 3 = 1,
) {
  return {
    id: `school-${id}-v1`,
    version: 1,
    topicId,
    conceptIds: [topicId],
    title,
    prompt,
    explanation,
    hint,
    difficulty,
    reviewable: false,
    provenance: schoolLessons.find((l) => l.topicId === topicId)!.provenance,
  }
}
const n = (
  t: string,
  id: string,
  title: string,
  prompt: string,
  answer: number,
  unit: Unit,
  explanation: string,
  hint: string,
  difficulty: 1 | 2 | 3 = 1,
): Exercise => ({
  ...base(t, id, title, prompt, explanation, hint, difficulty),
  type: 'numeric',
  answer,
  unit,
  tolerance: Math.max(Math.abs(answer) * 0.001, 1e-9),
})
const c = (
  t: string,
  id: string,
  title: string,
  prompt: string,
  choices: string[],
  explanation: string,
  hint: string,
  difficulty: 1 | 2 | 3 = 1,
): Exercise => {
  const options = choices.map((text, i) => ({ id: `o${i}`, text }))
  const offset = [...id].reduce((sum, ch) => sum + ch.charCodeAt(0), 0) % options.length
  return {
    ...base(t, id, title, prompt, explanation, hint, difficulty),
    type: 'choice',
    options: [...options.slice(offset), ...options.slice(0, offset)],
    answer: 'o0',
  }
}
