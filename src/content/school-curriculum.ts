export const schoolTopics: Topic[] = definitions.map(([id, title, area, prerequisites]) => ({
  id,
  title,
  area,
  subjectId: 'electrical',
  description: title,
  prerequisites,
  tier:
    id === 'ac-sine' || id === 'motor-force' || id === 'plc-bits'
      ? 2
      : id === 'ac-rms' || id === 'motor-build' || id === 'plc-generator'
        ? 3
        : id === 'plc-workflow'
          ? 5
          : 4,
  color:
    area === 'Wechselstromtechnik'
      ? 'blue'
      : area === 'Gleichstrommaschinen'
        ? 'amber'
        : 'lavender',
  ...(area !== 'SPS-Grundlagen'
    ? { lab: area === 'Wechselstromtechnik' ? ('ac' as const) : ('motor' as const) }
    : {}),
}))
// Same-tier dependencies need a strictly increasing authoring tier.
for (const topic of schoolTopics)
  topic.tier = Math.max(
    topic.tier,
    ...topic.prerequisites.map((id) => (schoolTopics.find((t) => t.id === id)?.tier ?? 1) + 1),
  )
